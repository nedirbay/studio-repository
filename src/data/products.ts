// Helper function to generate multiple images
function generateImages(baseImage: string): string[] {
  const baseUrl = baseImage.split('?')[0]
  return [
    `${baseUrl}?auto=compress&cs=tinysrgb&w=800`,
    `${baseUrl}?auto=compress&cs=tinysrgb&w=800&flip=h`,
    `${baseUrl}?auto=compress&cs=tinysrgb&w=800&sat=-100`,
    `${baseUrl}?auto=compress&cs=tinysrgb&w=800&brightness=-10`,
  ]
}

